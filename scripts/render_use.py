#!/usr/bin/env python3
"""Render the pictures of the embosser in use, for the User Guide.

Each picture is the complete embosser, from the placed bodies in
``build/renders/bodies/`` (the split assembled example plus the example
cylinders, as scripts/render_parts.py makes them), posed as the User Guide's
step says: standing with the Handle at home; lying on its side with the slit
up and the Handle to the right; a card standing in the slit; turned over
with the window up and the card coming out, its dots raised; the Lid lifted
off with the Knob and Handle. A red dashed arrow or arc marks the move the
step asks for, and the camera stands where the user sits, in front of the
embosser and a little above it. The pictures go to ``Photos/renders/
render-use-NN-<what>.png`` and are registered in images.json.

Usage:
    python scripts/render_use.py            # every picture
    python scripts/render_use.py --list

Local lane: needs trimesh and the OpenSCAD 2026.01.03 nightly (never run
with ``python -I``). License: GPL-3.0-or-later
"""

