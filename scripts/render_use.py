def _vec(v: Sequence[float]) -> str:
    return "[" + ", ".join(f"{x:g}" for x in v) + "]"


def scad_text(bodies: Dict[str, Path], spec: Dict) -> str:
    """One picture's OpenSCAD: the bodies posed, the card, the arrow."""
    pose = spec["pose"]
    lines = [
        "// Generated by scripts/render_use.py. Do not edit; rerun the script.",
        f"$vpt = {_vec(spec['cam'][0])}; $vpd = {spec['cam'][1]:g}; $vpr = {_vec(spec['rot'])};",
        "module dashed_arrow(from, to) {",
        "  d = to - from; len = norm(d);",
        "  rz = atan2(d[1], d[0]); ry = acos(d[2] / len);",
        "  translate(from) rotate([0, ry, rz]) {",
        "    for (s = [0 : 6 : max(0, len - 12)]) translate([0, 0, s]) cylinder(r = 1.0, h = 3.5, $fn = 16);",
        "    translate([0, 0, len - 7]) cylinder(r1 = 3.0, r2 = 0, h = 7, $fn = 24);",
        "  }",
        "}",
        "// A clockwise arc over the Handle, seen from above, with a head at one or both ends.",
        "module turn_arc(angle, both) {",
        f"  translate({_vec(HANDLE_AXIS)}) {{",
        "    rotate([0, 0, -angle / 2]) rotate_extrude(angle = angle, $fn = 72) translate([44, 0]) circle(r = 1.1, $fn = 12);",
        "    rotate([0, 0, -angle / 2]) translate([44, 0, 0]) rotate([0, 0, -90]) rotate([0, 90, 0]) cylinder(r1 = 3.0, r2 = 0, h = 7, $fn = 24);",
        "    if (both) rotate([0, 0, angle / 2]) translate([44, 0, 0]) rotate([0, 0, 90]) rotate([0, 90, 0]) cylinder(r1 = 3.0, r2 = 0, h = 7, $fn = 24);",
        "  }",
        "}",
        # The card: its 52 mm edge along the cylinders, its 90 mm length
        # along the path, a few rows of dots on the face that comes out raised.
        # Only the length that is out carries dots; past its edge they would
        # hang in the air.
        "module card(along, dots) {",
        f"  translate([{NIP[0]:g} - {CARD_T / 2:g}, 0, {CYL_Z[0]:g}]) cube([{CARD_T:g}, along, {CARD_H:g}]);",
        "  if (dots) for (r = [0 : 2], c = [0 : 10]) let (y = 8 + c * 6.5 + (r % 2) * 2) if (y < along - 3)",
        f"    translate([{NIP[0]:g} + {CARD_T / 2:g}, y, {CYL_Z[0]:g} + 40 - r * 10]) sphere(r = 0.7, $fn = 12);",
        "}",
    ]
    for pid, path in bodies.items():
        lines.append(f'module body_{pid.replace("-", "_")}() color("{PART_COLOURS[pid]}") import("{path.resolve().as_posix()}");')
    # The embosser in its pose: standing as modelled; lying on its side with
    # the slit (+y) up and the Handle end (+z) to the right; or turned over
    # from that, window up.
    frame = {"standing": "", "lying": "rotate([90, 0, 0]) rotate([0, 90, 0])",
             "over": "rotate([180, 0, 0]) rotate([90, 0, 0]) rotate([0, 90, 0])"}[pose]
    lines.append(f"{frame} {{")
    turn = spec.get("turn", 0.0) * 360
    lift = spec.get("lift", 0.0)
    for pid in bodies:
        name = pid.replace("-", "_")
        up = f"translate([0, 0, {lift:g}]) " if pid in TOP and lift else ""
        spin = f"translate([-30, 0, 0]) rotate([0, 0, {-turn:g}]) translate([30, 0, 0]) " if turn and pid in ("knob", "handle", "cylinder-a", "top-gear-a", "bottom-gear-a") else ""
        lines.append(f"  {up}{spin}body_{name}();")
    card = spec.get("card")
    if card:
        where, along = card
        if where == "slit":
            lines.append(f'  color("{CARD_COLOUR}") card({along:g}, false);')
        elif where == "window":
            lines.append(f'  color("{CARD_COLOUR}") mirror([0, 1, 0]) card({along:g}, true);')
    if spec.get("arrow") == "down":
        a, b = (NIP[0], card[1] + 22, 27), (NIP[0], card[1] + 4, 27)
        lines.append(f'  color("{ARROW_COLOUR}") dashed_arrow({_vec(a)}, {_vec(b)});')
    if spec.get("arrow") == "up":
        lines.append(f'  color("{ARROW_COLOUR}") dashed_arrow([-52, -20, 75], [-52, -20, 75 + {lift:g} - 4]);')
    if turn:
        lines.append(f'  color("{ARROW_COLOUR}") turn_arc({min(300, turn):g}, {"true" if spec.get("both") else "false"});')
    lines.append("}")
    if card and card[0] == "out":
        # The finished card flat on the table in front of the embosser, dots up.
        lines.append(f'color("{CARD_COLOUR}") translate([20, -100, -35]) cube([{CARD_W:g}, {CARD_H:g}, {CARD_T:g}]);')
        lines.append(f'color("{CARD_COLOUR}") for (r = [0 : 2], c = [0 : 10]) translate([20 + 8 + c * 6.5 + (r % 2) * 2, -100 + 40 - r * 10, -35 + {CARD_T:g}]) sphere(r = 0.7, $fn = 12);')
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", type=int, action="append", default=[], metavar="N", help="one picture by number (repeatable)")
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args(argv)
    if args.list:
        for p in PICTURES:
            print(f"{p['n']:2} render-use-{p['n']:02}-{p['slug']}")
        return 0
    bodies = split_bodies()
    BUILD.mkdir(parents=True, exist_ok=True)
    for spec in PICTURES:
        if args.only and spec["n"] not in args.only:
            continue
        name = f"render-use-{spec['n']:02}-{spec['slug']}"
        out = render(name, scad_text(bodies, spec), camera="", fit=False)
        register(name, out, {"kind": "use", "ids": ALL, "shows": spec["shows"]})
        print(f"{out.relative_to(ROOT).as_posix()} {out.stat().st_size // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
